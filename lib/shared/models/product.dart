class Product {
  static const double minimumPrice = 1600;

  const Product({
    required this.id,
    required this.name,
    required this.category,
    required this.price,
    required this.image,
    this.images = const [],
    this.rating = 0,
    this.soldCount = 0,
    this.description = '',
    this.colors = const [],
    this.material = '',
    this.dimensions = '',
    this.packageId = '',
    this.packageTitle = '',
  });

  final String id;
  final String name;
  final String category;
  final double price;
  final String image; // asset path ya network URL
  final List<String> images;
  final double rating;
  final int soldCount;
  final String description;
  final List<int> colors; // Color value, jaise 0xFFA0624A
  final String material;
  final String dimensions;
  final String packageId;
  final String packageTitle;

  Product copyWith({
    String? id,
    String? name,
    String? category,
    double? price,
    String? image,
    List<String>? images,
    double? rating,
    int? soldCount,
    String? description,
    List<int>? colors,
    String? material,
    String? dimensions,
    String? packageId,
    String? packageTitle,
  }) {
    return Product(
      id: id ?? this.id,
      name: name ?? this.name,
      category: category ?? this.category,
      price: price ?? this.price,
      image: image ?? this.image,
      images: images ?? this.images,
      rating: rating ?? this.rating,
      soldCount: soldCount ?? this.soldCount,
      description: description ?? this.description,
      colors: colors ?? this.colors,
      material: material ?? this.material,
      dimensions: dimensions ?? this.dimensions,
      packageId: packageId ?? this.packageId,
      packageTitle: packageTitle ?? this.packageTitle,
    );
  }

  /// Firestore document se Product banane ke liye.
  factory Product.fromMap(Map<String, dynamic> map, {String? id}) {
    final price = (map['price'] as num?)?.toDouble() ?? 0;
    return Product(
      id: id ?? (map['id'] as String? ?? ''),
      name: map['name'] as String? ?? '',
      category: map['category'] as String? ?? '',
      price: price > 0 && price < minimumPrice ? minimumPrice : price,
      image: map['image'] as String? ?? '',
      images: List<String>.from(map['images'] as List? ?? const []),
      rating: (map['rating'] as num?)?.toDouble() ?? 0,
      soldCount: (map['soldCount'] as num?)?.toInt() ?? 0,
      description: map['description'] as String? ?? '',
      colors: List<int>.from(map['colors'] as List? ?? const []),
      material: map['material'] as String? ?? '',
      dimensions: map['dimensions'] as String? ?? '',
      packageId: map['packageId'] as String? ?? '',
      packageTitle: map['packageTitle'] as String? ?? '',
    );
  }

  Map<String, dynamic> toMap() {
    return {
      'id': id,
      'name': name,
      'category': category,
      'price': price,
      'image': image,
      'images': images,
      'rating': rating,
      'soldCount': soldCount,
      'description': description,
      'colors': colors,
      'material': material,
      'dimensions': dimensions,
    };
  }

